#!/usr/bin/env bash
# Stage 3: regenerates the TypeScript wrapper from the merged SDK and builds the npm package with the preview version.
# Mirrors .github/workflows/generate_typescript.yml, then the packaging of the-forge publish workflows.
#
# Output: <work-dir>/sdk/ts-wrapper/build/tsPackage
#
# Usage: 03-build-ts-package.sh <work-dir>
set -euo pipefail
. "$(dirname "${BASH_SOURCE[0]}")/lib.sh"
load_state "${1:-}"

reset_sdk_paths ts-wrapper/src
cd "$SDK_DIR"
TS_PACKAGE="$SDK_DIR/ts-wrapper/build/tsPackage"
# The version must be a release version, else the build uses a snapshot version derived from the git tags.
GRADLE=(./gradlew "-PsdkVersion=$VERSION")

log "Generating the JSON representation of the SDK and clearing the generated TypeScript wrapper"
# Stale JSON of a previous run would be read by the wrapper generator: always start from an empty KSP output.
rm -rf cardinal-sdk/build/generated/ksp/jvm/jvmMain/resources
"${GRADLE[@]}" :cardinal-sdk:kspKotlinJvm --rerun :ts-wrapper:clearAutoGenerated

log "Generating the TypeScript wrapper (wrapper-codegen $WRAPPER_CODEGEN_VERSION)"
java -jar "$WRAPPER_JAR" generate --ts --input=cardinal-sdk/build/generated/ksp/jvm/jvmMain/resources

log "Building the npm package $NPM_PACKAGE@$VERSION"
rm -rf "$TS_PACKAGE"
"${GRADLE[@]}" :ts-wrapper:updateAutoGenerated :ts-wrapper:prepareDistributionPackage

PACKAGE_ID="$(node -p 'const p = require(process.argv[1]); p.name + "@" + p.version' "$TS_PACKAGE/package.json")"
[ "$PACKAGE_ID" = "$NPM_PACKAGE@$VERSION" ] || die "the package is $PACKAGE_ID, expected $NPM_PACKAGE@$VERSION"

# Only the generated paths: the worktree also holds local.properties, with credentials.
git add -A -- ts-wrapper/src
if ! git diff --cached --quiet; then
	git -c user.name="cardinal-preview" -c user.email="dev@icure.com" -c commit.gpgsign=false \
		commit --quiet -m "Preview $VERSION: TypeScript wrapper"
fi
log "Built $PACKAGE_ID in $TS_PACKAGE"
